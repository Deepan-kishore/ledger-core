package ledger.record;

/** Stable, machine-readable reasons why an event was rejected or declined. */
public enum ErrorCode {
    // input validation
    MISSING_SOURCE_ID,
    UNKNOWN_ACCOUNT,
    UNSUPPORTED_CURRENCY,
    CURRENCY_MISMATCH,
    INVALID_AMOUNT,
    EXCESS_PRECISION,
    NEGATIVE_AMOUNT,
    ZERO_AMOUNT,
    INVALID_BOOKED_DAY,
    INVALID_VALUE_DAY,
    MISSING_AUTHORIZATION_ID,
    INVALID_INSTALMENT_COUNT,
    WINDOW_FINALIZED,
    // idempotency
    DUPLICATE_SOURCE_CONFLICT,
    // authorization / settlement
    DUPLICATE_AUTHORIZATION_ID,
    INSUFFICIENT_AVAILABLE_FUNDS,
    UNKNOWN_AUTHORIZATION,
    AUTHORIZATION_DECLINED,
    AUTHORIZATION_ALREADY_SETTLED,
    AUTHORIZATION_ACCOUNT_MISMATCH,
    CAPTURE_EXCEEDS_HOLD,
    // reversal
    REVERSAL_TARGET_NOT_FOUND,
    REVERSAL_TARGET_NOT_ACCEPTED,
    REVERSAL_UNSUPPORTED_TARGET,
    REVERSAL_ACCOUNT_MISMATCH,
    REVERSAL_VALUE_DAY_MISMATCH,
    REVERSAL_ALREADY_APPLIED,
    // fees
    MISSING_FEE_POLICY
}
